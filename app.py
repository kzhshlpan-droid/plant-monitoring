import streamlit as st
import cv2
import numpy as np

# Бет баптаулары
st.set_page_config(page_title="Ақылды өсімдік мониторингі", page_icon="🌱", layout="centered")

st.title("🌱 Өсімдіктер мониторингі және авто-диагностика")
st.caption("Өсімдік аурулары мен дефициттерді түстік сегментация арқылы талдау")

uploaded_file = st.file_uploader("Өсімдік суретін жүктеңіз...", type=["jpg", "jpeg", "png"])

if uploaded_file is not None:
    # 1. Суретті жүктеу және өлшемін реттеу
    file_bytes = np.asarray(bytearray(uploaded_file.read()), dtype=np.uint8)
    image = cv2.imdecode(file_bytes, 1)
    
    height, width, _ = image.shape
    aspect_ratio = width / height
    new_width = 600
    new_height = int(new_width / aspect_ratio)
    image = cv2.resize(image, (new_width, new_height))
    
    # 2. HSV түс кеңістігіне өту
    hsv = cv2.cvtColor(image, cv2.COLOR_BGR2HSV)
    
    # Түстік сегментация (Диапазондар)
    green_mask = cv2.inRange(hsv, np.array([35, 40, 40]), np.array([85, 255, 255]))
    yellow_mask = cv2.inRange(hsv, np.array([15, 40, 40]), np.array([35, 255, 255]))
    brown_mask = cv2.inRange(hsv, np.array([10, 40, 20]), np.array([20, 255, 200]))
    
    # Түстердің пайыздық үлесін есептеу
    total_pixels = image.shape[0] * image.shape[1]
    green_pct = (cv2.countNonZero(green_mask) / total_pixels) * 100
    yellow_pct = (cv2.countNonZero(yellow_mask) / total_pixels) * 100
    brown_pct = (cv2.countNonZero(brown_mask) / total_pixels) * 100
    other_pct = max(0.0, 100.0 - (green_pct + yellow_pct + brown_pct))
    
    # Суретті көрсету
    st.image(cv2.cvtColor(image, cv2.COLOR_BGR2RGB), caption="Түпнұсқа сурет", use_container_width=True)
    
    # -------------------------------------------------------------
    # 1-БӨЛІМ: ДИАГНОСТИКА КЕСТЕСІ (ЕСЕПТЕЛГЕН МӘНДЕР)
    # -------------------------------------------------------------
    st.header("📊 Мониторинг және Талдау Нәтижесі")
    
    st.table({
        "Көрсеткіш": [
            "Сау өсімдік (Жасыл)", 
            "Ауру/Сарғайған (Сары)", 
            "Құрғап қалған (Қоңыр)", 
            "Қоршаған орта / Бөлме"
        ],
        "Пайыздық үлесі": [
            f"{green_pct:.2f}%", 
            f"{yellow_pct:.2f}% " + ("⚠️" if yellow_pct > 10 else "✅"), 
            f"{brown_pct:.2f}% " + ("🚨" if brown_pct > 5 else "✅"), 
            f"{other_pct:.2f}%"
        ]
    })
    
    # -------------------------------------------------------------
    # 2-БӨЛІМ: ДИНАМИКАЛЫҚ ДИАГНОСТИКА (СУРЕТКЕ НАҚТЫ ТАЛДАУ)
    # -------------------------------------------------------------
    st.header("🔬 Автоматты Диагностика")
    
    unhealthy_pct = yellow_pct + brown_pct
    
    # А) САРҒАЙҒАН АЙМАҚ ТАЛДАУЫ (ХЛОРОЗ / ЭЛЕМЕНТ ЖЕТІСПЕУШІЛІГІ)
    if yellow_pct > 10:
        st.subheader("⚠️ 1. Тамыр элементтерінің жетіспеушілігі (Азот / Темір дефициті)")
        st.write(f"Суретте **{yellow_pct:.1f}%** сары аймақ анықталды. Бұл хлороз немесе минералдардың жетіспеушілігін көрсетеді:")
        st.table({
            "Элемент": ["Азот (N) жетіспеушілігі", "Темір (Fe) жетіспеушілігі"],
            "Белгісі": [
                "Ескі/төменгі жапырақтар сарғайып, өсу баяулайды.",
                "Жас жапырақтар сарғаяды, бірақ тамыршалары жасыл болып қалады."
            ],
            "Емі / Шешімі": [
                "Аммиак селитрасы немесе мочевина (1-2 г/л су) қосып суару.",
                "Темір хелатының 0.1% ерітіндісін жапыраққа шашу."
            ]
        })
    
    # Б) ҚҰРҒАП ҚАЛҒАН АЙМАҚ ТАЛДАУЫ (ЫЛҒАЛДЫЛЫҚ / СУАРУ ПРАВИЛАСЫ)
    if brown_pct > 3:
        st.subheader("🚨 2. Суару және Ауа ылғалдылығы проблемасы")
        st.write(f"Өсімдікте **{brown_pct:.1f}%** құрғаған/қоңыр бөліктер бар. Бұл тікелей физиологиялық стресті білдіреді:")
        st.table({
            "Себебі": ["Ауа құрғақтығы", "Судың жетіспеушілігі немесе тамыр шірігі"],
            "Анықтамасы": [
                "Жапырақ ұштары мен шеттері қарайып, бұйраланады.",
                "Бүршіктер мен гүлдер қуарады, өсімдік солып қалады."
            ],
            "Шешімі": [
                "Бөлме ылғалдылығын 60-80%-ға дейін арттыру, су бүрку.",
                "Топырақ ылғалдылығын тексеру, қажет болса тамырды жаңа топыраққа ауыстыру."
            ]
        })

    # В) ҚОРЫТЫНДЫ СТАТУС БЕРУ
    st.subheader("📝 Жалпы Қорытынды Статус")
    if unhealthy_pct > 15:
        st.error(f"🚨 **Статус: НАЗАР АУДАРЫҢЫЗ!**\nЗақымдалған аймақ жалпы **{unhealthy_pct:.2f}%** құрайды. Өсімдікке жедел көмек қажет.")
    elif unhealthy_pct > 5:
        st.warning(f"⚠️ **Статус: ЕСКЕРТУ!**\nШамалы зақымдану байқалады ({unhealthy_pct:.2f}%). Күтімді күшейтіңіз.")
    else:
        st.success("✅ **Статус: ӨСІМДІК ЖАҒДАЙЫ ӨТЕ ЖАҚСЫ!**\nЖапырақтарда айтарлықтай ауру немесе дефицит белгілері анықталмады.")

    # -------------------------------------------------------------
    # 3-БӨЛІМ: СУРЕТКЕ НЕГІЗДЕЛГЕН АВТОМАТТЫ ҰСЫНЫСТАР
    # -------------------------------------------------------------
    st.header("💡 Автоматты генерацияланған Ұсыныстар")
    
    recommendations = []
    
    if yellow_pct > 10:
        recommendations.append("<b>Азотты тыңайтқыш беру:</b> Аммиак селитрасы немесе мочевина суын (1-2 г/л) қосыңыз.")
        recommendations.append("<b>Темір хелатын қолдану:</b> Жапыраққа 0,1% темір хелатын бүркіңіз (2 аптада 1 рет).")
        
    if brown_pct > 3:
        recommendations.append("<b>Ылғалдылықты арттыру:</b> Жапырақтарға күніне 1-2 рет су шашыратыңыз.")
        recommendations.append("<b>Құрғаған бөліктерді отау:</b> Қуарған гүлдер мен жапырақтарды кесіп тастаңыз.")
        
    if other_pct > 60:
        recommendations.append("<b>Фокусты реттеу:</b> Суретке тек өсімдік жапырағын жақыннан түсірсеңіз, талдау дәлдігі артады.")
        
    if not recommendations:
        recommendations.append("Суару және жарық режимін қазіргі қалыпты деңгейде сақтаңыз.")
        recommendations.append("Алдын алу үшін айына 1 рет кешенді минералды тыңайтқыш беріңіз.")

    # Ұсыныстарды кестемен шығару
    steps = [f"{i+1}️⃣" for i in range(len(recommendations))]
    st.table({
        "Қадам": steps,
        "Іс-әрекет ұсынысы": recommendations
    })
